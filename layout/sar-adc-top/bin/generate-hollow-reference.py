#!/usr/bin/env python3
"""Derive the `--abstract-cells` LVS reference (issue #103) from the flow's own
full top-level reference (`sar_adc_top.lvs-reference.spice`, written by
generate-lvs-reference.py).

The layout side of this compare black-boxes three already-independently-
verified macros (`klt extract --abstract-cells`), so the reference side must
carry the same shape (see README.md, "A fourth shape measured"):

  * cdac_array, sar_sequencer, top_glue: subckt renamed to the
    `<block-id>__<cell-name>` qualifier `klt gen-compose` gives the layout
    side, and HOLLOWED (header + `.ENDS` only) -- their device-level
    topology is verified in each sub-block's own flow, so this compare is
    pure top-level interconnect for them.
  * comparator, sampling_frontend, halflsb_offset: INLINED into
    `.SUBCKT sar_adc_top` (they stay flat on the layout side). Each port is replaced by the top-level net
    its `X` line connects it to; every other net is prefixed `<INST>_`;
    device designators keep their first character and gain the `<INST>`
    prefix (so `NetlistSpiceReader` still classifies M/C cards).
  * top-level primitive cards (DR-017's decoupling `C` cards, issue #440):
    kept verbatim -- they are top-level devices on both sides already.

`seln_inverters` (the pre-#401 composition, DR-008-superseded) is still listed
so this script reproduces the 2026-10-03 records' hollow reference from their
own full reference; a macro absent from the input reference is skipped.

No device-level content is introduced: every card is copied from the full
reference. Usage:

    generate-hollow-reference.py <full-reference.spice> -o <out.spice>
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

HOLLOW = {
    "cdac_array": "cdac_array__cdac_array",
    "sar_sequencer": "sar_sequencer__sar_sequencer",
    "top_glue": "top_glue__top_glue",
    "seln_inverters": "seln_inverters__seln_inverters",
}
INLINE = ("sampling_frontend", "comparator", "halflsb_offset")


def parse(text: str):
    """Return ({subckt: (ports, [body lines])}, [top body lines], top header)."""
    # Join `+` continuation lines.
    lines: list[str] = []
    for raw in text.splitlines():
        if raw.startswith("+") and lines:
            lines[-1] += " " + raw[1:].strip()
        else:
            lines.append(raw.rstrip())
    subckts: dict[str, tuple[list[str], list[str]]] = {}
    cur = None
    for ln in lines:
        s = ln.strip()
        if s.upper().startswith(".SUBCKT"):
            toks = s.split()
            cur = toks[1]
            subckts[cur] = (toks[2:], [])
        elif s.upper().startswith(".ENDS"):
            cur = None
        elif cur is not None and s and not s.startswith("*"):
            subckts[cur][1].append(s)
    return subckts


def inline(inst: str, sub: tuple[list[str], list[str]], conns: list[str]) -> list[str]:
    ports, body = sub
    if len(ports) != len(conns):
        raise SystemExit(f"{inst}: {len(ports)} ports vs {len(conns)} connections")
    netmap = dict(zip(ports, conns))
    out = []
    for card in body:
        toks = card.split()
        name = toks[0]
        kind = name[0].upper()
        if kind == "M":
            nn, tail_start = 4, 5
        elif kind == "C":
            nn, tail_start = 2, 3
        else:
            raise SystemExit(f"{inst}: unsupported card {card!r}")
        nets = [netmap.get(n, f"{inst}_{n}") for n in toks[1:1 + nn]]
        new_name = f"{name[0]}{inst}{name[1:]}"
        out.append(" ".join([new_name, *nets, *toks[tail_start:]]))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("full_reference", type=Path)
    ap.add_argument("-o", "--out", required=True, type=Path)
    args = ap.parse_args()

    subs = parse(args.full_reference.read_text())
    top_ports, top_body = subs["sar_adc_top"]

    out: list[str] = [
        "* GENERATED by layout/sar-adc-top/bin/generate-hollow-reference.py from the",
        "* flow's own sar_adc_top.lvs-reference.spice -- DO NOT HAND-EDIT.",
        "* Hollowed macros + inlined comparator/sampling_frontend/halflsb_offset: the reference",
        "* shape for `klt extract --abstract-cells` (README.md).",
    ]
    for name, qual in HOLLOW.items():
        if name not in subs:
            continue
        ports, _ = subs[name]
        out += [f".SUBCKT {qual} {' '.join(ports)}", f".ENDS {qual}"]

    out.append(f".SUBCKT sar_adc_top {' '.join(top_ports)}")
    inlined: list[str] = []
    kept: list[str] = []
    for card in top_body:
        toks = card.split()
        if toks[0][0].upper() == "X":
            inst, model, conns = toks[0], toks[-1], toks[1:-1]
            if model in INLINE:
                inlined += inline(inst[1:].upper(), subs[model], conns)
                continue
            if model in HOLLOW:
                kept.append(" ".join([*toks[:-1], HOLLOW[model]]))
                continue
            raise SystemExit(f"unexpected instance {card!r}")
        if toks[0][0].upper() in "MC":
            kept.append(card)
            continue
        raise SystemExit(f"unexpected top card {card!r}")
    out += inlined + kept
    out.append(".ENDS sar_adc_top")
    args.out.write_text("\n".join(out) + "\n")
    print(f"generate-hollow-reference.py: wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
