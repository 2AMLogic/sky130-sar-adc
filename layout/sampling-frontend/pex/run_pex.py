#!/usr/bin/env python3
"""Sampling front end sub-block PEX flow (issue #1017): schematic-vs-extracted
comparison of the acquisition-window settling experiment
(timing and input step from `sim/sampling-acquisition-settling`, issues #121/#236,
with SAMPLE high fixed at 1.8 V), at
the ratified 9-point one-at-a-time PVT corner set -- the DR-006 worst-case
(12 MHz) per-phase budget probe (`budget_*`, a fixed-time read one phase
period after the second SAMPLE rising edge), its confirmatory long-window
read (`confirm_*`), and the campaign's 50%/90% crossing delays, on TOP_P/
TOP_N and on the bootstrap rails BOOST_P/BOOST_N.

Two `klt` calls per record, on the layout flow's pinned `klt`
(layout/requirements.txt) through layout/bin/pex_flow.py:

1. `klt extract --parasitics --pdk sky130A` -- the full per-net R/C table
   (TOP_x/BOOST_x/BPREF_x parasitic R/C behind the delta rows).
2. `klt pex <sampling_frontend.gds> <request.json>` -- extracts again and
   re-simulates both legs of the settling testbench (`testbench.spice`)
   across the corner grid, reporting per-corner, per-measure `delta[]` rows.

The schematic DUT (`sampling_frontend_pex_reference.spice`, materialized per
run) wraps the committed regenerated fragment
`sim/sampling-frontend/testbench/sampling_frontend_dut.spice` (issue #52 --
the same fragment the acquisition campaign itself instantiates) in the
EXTRACTED netlist's own `.SUBCKT` name and pin order, so `klt pex`'s
DUT-`.include`-swap convention has a pin-identical schematic leg (the
comparator flow's convention, issue #112). The fragment's trailing
`.GLOBAL GND` line is dropped in the wrap: inside a `.SUBCKT` whose formal
pin list names GND, a global declaration would shadow the port binding; the
testbench ties the GND pin to node 0 directly, which is what the flat
fragment's `.GLOBAL GND` achieved anyway.

The COMBINED front-end + CDAC-array load (`sim/sampling-cdac-handoff`'s
question) is deliberately NOT run here: that testbench instantiates two
separate layout tops, and `klt pex` extracts exactly one `--top` per run
and swaps a single DUT `.include` -- the multi-top gap
2AMLogic/klayout-tools#5494 tracks, and the composed-block run blocked on
issue #103's top-level LVS. This record measures the front end's own
parasitic contribution at its own Csamp load, and says so.

    layout/bin/setup-venv.sh                     # once (pinned klt)
    source sim/env.sh                            # exports PDK_ROOT/PDK
    python3 layout/sampling-frontend/pex/run_pex.py --check-env
    python3 layout/sampling-frontend/pex/run_pex.py --pilot    # tt/27C/1.8V, local
    python3 layout/sampling-frontend/pex/run_pex.py --record   # 9 OAT corners, batch

Each `--record` run mints a new timestamped, append-only record under
`layout/sampling-frontend/reports/<record-id>/`; it never edits a prior
record and never touches `reports/LATEST` (the drawing flow's pointer).
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
import tempfile
from pathlib import Path

PEX_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(PEX_DIR.parents[1] / "bin"))
sys.path.insert(0, str(PEX_DIR.parents[2] / "sim"))

import pex_flow  # noqa: E402

from harness import evidence  # noqa: E402

BLOCK_DIR = PEX_DIR.parent
REPORTS_DIR = BLOCK_DIR / "reports"
GDS_NAME = "sampling_frontend.gds"

#: The extracted interface this flow's committed testbench.spice hardcodes
#: (its Xdut line is positional). Asserted against every run's own extraction
#: before anything simulates -- a re-draw that reorders pins fails loudly.
EXPECTED_SUBCKT = "gen_compose_0"
EXPECTED_PINS = ["BOOST_N", "BOOST_P", "BPREF_N", "BPREF_P", "GND", "SAMPLE",
                 "TOP_N", "TOP_P", "VCM", "VDD", "VINN", "VINP"]

#: The committed regenerated DUT fragment the acquisition campaign itself
#: instantiates (sim/sampling-frontend/, issue #52).
DUT_FRAGMENT = PEX_DIR.parents[2] / "sim" / "sampling-frontend" / "testbench" / "sampling_frontend_dut.spice"

# Campaign constants (sim/sampling-acquisition-settling), restated so the
# testbench and this request builder cannot drift apart.
TRIG_AT_NS = 160.1                 # 50% of SAMPLE#2's rising edge
T_PHASE_WORST_NS = 1.0e3 / 12.0    # DR-006 worst-case 12 MHz phase period
BUDGET_AT_NS = TRIG_AT_NS + T_PHASE_WORST_NS
CONFIRM_AT_NS = 305.0
TRAN_STOP_NS = 330.0
TRAN_STEP_NS = 0.02
V_FINAL = {"p": 1.6, "n": 0.2}
V_INITIAL = {"p": 0.2, "n": 1.6}
SIDES = ("p", "n")


def dut_fragment() -> str:
    """The committed regenerated fragment, verbatim minus its `.GLOBAL GND`
    line (see module docstring) -- the schematic leg IS the campaign's own
    DUT, not a re-derivation."""
    lines = [
        "* sampling_frontend_pex_reference.spice -- schematic-equivalent DUT",
        "* for this `klt pex` run (issue #1017), GENERATED by run_pex.py:",
        "* sim/sampling-frontend/testbench/sampling_frontend_dut.spice",
        "* (issue #52, byte-identical device cards -- the same fragment",
        "* sim/sampling-acquisition-settling instantiates) minus its trailing",
        "* `.GLOBAL GND` (a global would shadow the GND port inside this",
        "* wrapper; the testbench ties GND to node 0 directly), wrapped in",
        "* the extracted netlist's own .SUBCKT name and pin order (asserted",
        "* equal to testbench.spice's hardcoded list before this file was",
        "* written).",
    ]
    body = [
        ln for ln in DUT_FRAGMENT.read_text().splitlines()
        if not ln.strip().lower().startswith(".global")
    ]
    return "\n".join(lines) + "\n" + "\n".join(body)


def measurements() -> list[dict]:
    rows: list[dict] = []
    for side in SIDES:
        node = f"top_{side}"
        v_i, v_f = V_INITIAL[side], V_FINAL[side]
        for frac in (0.5, 0.9):
            target = v_i + frac * (v_f - v_i)
            name = f"t_settle_{side}_{int(frac * 100)}"
            rows.append({
                "name": name,
                "spice": (
                    f".meas tran {name} TRIG AT={TRIG_AT_NS}n TARG V({node}) "
                    f"VAL={target:.8g} TD={TRIG_AT_NS}n CROSS=1"
                ),
                "unit": "s",
            })
        rows.append({
            "name": f"budget_{side}",
            "spice": f".meas tran budget_{side} find v({node}) at={BUDGET_AT_NS}n",
            "unit": "V",
        })
        rows.append({
            "name": f"confirm_{side}",
            "spice": f".meas tran confirm_{side} find v({node}) at={CONFIRM_AT_NS}n",
            "unit": "V",
        })
    for side in SIDES:
        for stat, at in (("budget", BUDGET_AT_NS), ("confirm", CONFIRM_AT_NS)):
            name = f"boost_{side}_{stat}"
            rows.append({
                "name": name,
                "spice": f".meas tran {name} find v(boost_{side}) at={at}n",
                "unit": "V",
            })
    return rows


def build_request(points) -> dict:
    corners, exclude = pex_flow.build_corners_spec(points)
    return {
        "netlist": "testbench.spice",
        "engine": "ngspice",
        "models": {"pdk": "sky130A", "lib": "libs.tech/combined/sky130.lib.spice"},
        "corners": corners,
        "exclude": exclude,
        "analysis": {"kind": "tran", "args": f"{TRAN_STEP_NS}n {TRAN_STOP_NS}n"},
        "measurements": measurements(),
        "options": {"timeout_s": 900, "keep_artifacts": False},
    }


def oat_points(pilot: bool):
    # Only vdd varies. Vcm and VIN follow the campaign's fixed levels.
    # This PEX bench also fixes SAMPLE high at 1.8 V.
    pts = pex_flow.ratified_oat_points({})
    if pilot:
        pts = [p for p in pts if p.cid == "tt_27c_1.80v"]
    return pts


def run(work_dir: Path, backend: str, pilot: bool, record: bool, quiet: bool = False) -> int:
    info = pex_flow.resolve_pdk()
    gds_path, latest_id = pex_flow.latest_layout(BLOCK_DIR, GDS_NAME)

    work_dir.mkdir(parents=True, exist_ok=True)
    gds_rel = str(gds_path.resolve())

    # --- Step 1: klt extract --parasitics (per-net R/C table) --------------
    extract_json = pex_flow.extract_parasitics(
        Path(gds_rel), work_dir, "sampling_frontend.pex-extract.spice", info, quiet=quiet
    )
    (work_dir / "extract.json").write_text(json.dumps(extract_json, indent=2) + "\n")

    # --- Step 2: schematic DUT, wrapped in the extraction's own interface --
    name, pins = pex_flow.extracted_subckt(work_dir / "sampling_frontend.pex-extract.spice")
    if name != EXPECTED_SUBCKT or pins != EXPECTED_PINS:
        raise pex_flow.PexFlowError(
            f"extracted interface drifted from testbench.spice's hardcoded one:\n"
            f"  got .SUBCKT {name} {' '.join(pins)}\n"
            f"  want .SUBCKT {EXPECTED_SUBCKT} {' '.join(EXPECTED_PINS)}\n"
            f"Re-derive testbench.spice's Xdut line against the new pin list."
        )
    dut = pex_flow.wrap_dut(dut_fragment(), name, pins, "*")
    (work_dir / "sampling_frontend_pex_reference.spice").write_text(dut)

    # --- Step 3: klt pex -- both legs, all corners, one call ---------------
    shutil.copy(PEX_DIR / "testbench.spice", work_dir / "testbench.spice")
    points = oat_points(pilot)
    request = pex_flow.apply_capacity_wait(build_request(points))
    (work_dir / "pex_request.json").write_text(json.dumps(request, indent=2) + "\n")

    (work_dir / ".klt").mkdir(exist_ok=True)
    pex_json = pex_flow.run_klt(
        [
            "pex",
            gds_rel,
            "pex_request.json",
            "--deck",
            "sky130",
            "--pdk",
            info.variant,
            "--pdk-root",
            str(info.root),
            "-o",
            str((work_dir / ".klt" / "pex-extracted.spice").resolve()),
            "--outdir",
            str((work_dir / ".klt" / "pex").resolve()),
            "--backend",
            backend,
        ],
        cwd=work_dir,
        backend=backend,
        quiet=quiet,
    )
    (work_dir / "pex.json").write_text(json.dumps(pex_json, indent=2) + "\n")
    if pex_json.get("status") != "pass":
        print(f"klt pex did not pass: {json.dumps(pex_json)[:800]}", file=sys.stderr)
        return 1

    analysis = analyse(pex_json)
    report(analysis, quiet=quiet)

    if record:
        path = write_record(work_dir, latest_id, extract_json, pex_json, analysis)
        print(f"wrote {path}")
    shutil.rmtree(work_dir / ".klt", ignore_errors=True)
    return 0


def analyse(pex_json: dict) -> dict:
    """Per-corner settling analysis keyed off pex delta[]: per leg, the
    budget/confirm residuals against the NEW input value (the campaign's own
    error definition) and the 50%/90% crossing delays; plus the sch-vs-ext
    delta of every raw measure."""
    idx = pex_flow.delta_index(pex_json)
    out = {}
    for cid, rows in idx.items():
        process, temp, supplies = pex_flow.parse_corner_id(cid)
        per_leg = {}
        for leg in ("schematic", "extracted"):
            leg_rows = {}
            for side in SIDES:
                budget = rows.get(f"budget_{side}", {}).get(leg)
                confirm = rows.get(f"confirm_{side}", {}).get(leg)
                leg_rows[f"budget_err_{side}_mv"] = (
                    None if budget is None else (budget - V_FINAL[side]) * 1000.0
                )
                leg_rows[f"confirm_err_{side}_mv"] = (
                    None if confirm is None else (confirm - V_FINAL[side]) * 1000.0
                )
            for name in list(rows):
                if name.startswith("t_settle_") or name.startswith("boost_"):
                    leg_rows[name] = rows[name].get(leg)
            per_leg[leg] = leg_rows
        deltas = {}
        for name in set(rows):
            vs, ve = rows[name].get("schematic"), rows[name].get("extracted")
            if vs is not None and ve is not None:
                deltas[name] = ve - vs
        out[cid] = {
            "process": process, "temp_c": temp, "supplies": supplies,
            "legs": per_leg, "delta": deltas,
        }
    return out


def report(analysis: dict, *, quiet: bool) -> None:
    if quiet:
        return
    for cid, a in sorted(analysis.items()):
        sch, ext = a["legs"]["schematic"], a["legs"]["extracted"]
        def _f(v, unit_scale=1.0):
            return "n/a" if v is None else f"{v * unit_scale:.4f}"
        print(
            f"  {cid}: budget_err sch(P/N) {_f(sch['budget_err_p_mv'])}/{_f(sch['budget_err_n_mv'])} mV"
            f" | ext {_f(ext['budget_err_p_mv'])}/{_f(ext['budget_err_n_mv'])} mV"
            f" | t90 sch {_f(sch.get('t_settle_p_90'), 1e9)}ns ext {_f(ext.get('t_settle_p_90'), 1e9)}ns"
        )


def write_record(
    work_dir: Path, latest_id: str, extract_json: dict, pex_json: dict, analysis: dict
) -> Path:
    out = work_dir
    record_id = out.name
    for name in (
        "sampling_frontend.pex-extract.spice",
        "extract.json",
        "sampling_frontend_pex_reference.spice",
        "testbench.spice",
        "pex_request.json",
        "pex.json",
    ):
        src, dst = work_dir / name, out / name
        if src.resolve() != dst.resolve():
            shutil.copy(src, dst)

    prov = extract_json["provenance"]
    body_bias = pex_json.get("body_bias", {})
    model = pex_json.get("extraction", {}).get("model", {})
    nets = pex_flow.net_table(
        extract_json,
        {"TOP_P", "TOP_N", "BOOST_P", "BOOST_N", "BPREF_P", "BPREF_N"},
    )
    vsubs_present = ".GLOBAL vsubs" in (out / "sampling_frontend.pex-extract.spice").read_text()

    worst_budget = None
    worst_delta_mv = 0.0
    worst_delta_name = ""
    worst_cid = None
    for cid, a in analysis.items():
        for leg in ("schematic", "extracted"):
            for side in SIDES:
                v = a["legs"][leg].get(f"budget_err_{side}_mv")
                if v is not None and (worst_budget is None or abs(v) > abs(worst_budget[0])):
                    worst_budget = (v, cid, leg, side)
        for name, d in a["delta"].items():
            if (name.startswith("budget") or name.startswith("confirm")) and abs(d * 1000) > abs(worst_delta_mv):
                worst_delta_mv = d * 1000
                worst_delta_name, worst_cid = name, cid

    lines: list[str] = []
    a = lines.append
    a(f"# Sampling front end PEX record: {record_id}")
    a("")
    a(
        "Real `klt extract --parasitics --pdk sky130A` extraction of the sampling "
        f"front end layout `reports/{latest_id}/sampling_frontend.gds` and a `klt pex` "
        "schematic-vs-extracted comparison of the acquisition-window settling "
        "experiment (timing and input levels from `sim/sampling-acquisition-settling`, issues "
        "#121/#236: two SAMPLE pulses, full-scale differential input step during hold, "
        "DR-006 worst-case 12 MHz per-phase budget read one phase period after the "
        "second SAMPLE rising edge), at the ratified 9-point one-at-a-time PVT grid "
        "(spec/target-spec.md \"Numeric rows -- RATIFIED 2026-08-19\"). Generated by "
        "`layout/sampling-frontend/pex/run_pex.py` (issue #1017); re-run it to "
        "reproduce."
    )
    a("")
    a("## Provenance")
    a("")
    a(f"- {pex_flow.klt_version_note(prov['klt_version'])}")
    a(f"- KLayout engine: {prov['klayout_version']}")
    a(f"- PDK: {prov['pdk']['name']} ({prov['pdk']['version']})")
    a(f"- Extraction deck content hash: `{prov['deck']['content_hash']}`")
    a(
        f"- layout source: `layout/sampling-frontend/reports/{latest_id}/sampling_frontend.gds` "
        "(this flow only reads `reports/LATEST`, never moves it)"
    )
    a(f"- `body_bias.status`: **{body_bias.get('status', 'n/a')}** "
      f"({body_bias.get('unbiased_device_count', 0)} unbiased PMOS body nets) -- "
      "checked before any number below is read; an anonymous body net would make "
      "the extracted leg's resimulation physically wrong, not merely imprecise. "
      "This block's PFET bodies deliberately sit on BOOST_P/BOOST_N islands "
      "(DR-004/DR-007), which the extracted netlist resolves from the drawn wells."
    )
    a(
        "- `extraction.model` (klt pex's own scope note): capacitance = "
        f"{model.get('capacitance', 'n/a')}"
    )
    if vsubs_present:
        a(
            "- **Floating substrate net**: same condition as the CDAC record of this "
            "issue -- the extracted netlist declares `.GLOBAL vsubs` with no DC tie "
            "(klayout-tools#7066); the extracted leg's absolute node voltages include "
            "the substrate node's own motion. The sch-vs-ext delta rows below mix "
            "that artifact with the layout's own parasitics."
        )
    a("")
    a("## Extracted net R/C table (the nets the delta rows read through)")
    a("")
    a("| Net | R (ohm) | C to ground (fF) | C coupled, total (fF) | C total (fF) |")
    a("|---|---|---|---|---|")
    for n in ("TOP_P", "TOP_N", "BOOST_P", "BOOST_N", "BPREF_P", "BPREF_N"):
        t = nets.get(n, {})
        a(
            f"| {n} | {t.get('r_ohm', 0):.2f} | {t.get('c_ground_ff', 0):.4f} "
            f"| {t.get('c_coupled_total_ff', 0):.4f} | {t.get('c_total_ff', 0):.4f} |"
        )
    a("")
    a("## Schematic-vs-extracted settling delta (per corner)")
    a("")
    a(
        "Both PEX legs drive SAMPLE high to 1.8 V. The acquisition campaign drives "
        "it to VDD. At tt/27C the PEX clock is 0.18 V above the 1.62 V rail and "
        "0.18 V below the 1.98 V rail. The stronger NMOS gate drive at the low rail "
        "is expected to speed acquisition and reduce the budget residual, with the "
        "opposite tendency at the high rail. The extracted residuals below were "
        "measured only with the fixed clock. VCM (0.9 V), the input step "
        "(0.2 to 1.6 V or its reverse), and the read times match the campaign."
    )
    a("")
    a(
        "Per corner, per leg: `budget_err_x` = v(top_x) at the DR-006 budget point "
        f"minus the NEW input value (the campaign's own error definition); "
        f"`confirm_err_x` the same at {CONFIRM_AT_NS:g} ns; `t_settle_x_{{50,90}}` the "
        f"campaign's TRIG/TARG crossing delays from {TRIG_AT_NS:g} ns. Raw "
        "per-corner values in `pex.json`'s `delta[]`."
    )
    a("")
    a("| corner | vdd (V) | budget_err P sch/ext (mV) | budget_err N sch/ext (mV) | t_settle_P_90 sch/ext (ns) |")
    a("|---|---|---|---|---|")

    def _mv(v):
        return "n/a" if v is None else f"{v:.4f}"

    def _ns(v):
        return "n/a" if v is None else f"{v * 1e9:.4f}"

    for cid in sorted(analysis):
        x = analysis[cid]
        sch, ext = x["legs"]["schematic"], x["legs"]["extracted"]
        a(
            f"| `{cid}` | {x['supplies']['vdd']:.2f} "
            f"| {_mv(sch['budget_err_p_mv'])} / {_mv(ext['budget_err_p_mv'])} "
            f"| {_mv(sch['budget_err_n_mv'])} / {_mv(ext['budget_err_n_mv'])} "
            f"| {_ns(sch.get('t_settle_p_90'))} / {_ns(ext.get('t_settle_p_90'))} |"
        )
    a("")
    if worst_budget is not None:
        a(
            f"Headline: worst budget residual across the grid is "
            f"**{worst_budget[0]:.4f} mV** at `{worst_budget[1]}` ({worst_budget[2]} "
            f"leg, {worst_budget[3]} side); worst schematic-vs-extracted move on a "
            f"budget/confirm read is **{worst_delta_mv:.4f} mV** (`{worst_delta_name}` "
            f"at `{worst_cid}`). Where the delta rows come from -- the extracted "
            "netlist's own added R/C rather than a device change: the legs are "
            "device-identical by construction (`klt pex` swaps only the DUT "
            "`.include`), so every nonzero row is the extracted netlist's own "
            "parasitics plus the disclosed floating-substrate artifact. The table "
            "above names the carriers: TOP_x parasitic C loads the acquisition "
            "divider (a slower, smaller-step settle), BOOST_x parasitic C erodes the "
            "bootstrap rail the switch's overdrive depends on (the mechanism issue "
            "#236 identified on the schematic level, now measured as drawn), and the "
            "R column sets the redistribution time constants."
        )
    a("")
    a(
        "## Scope statement"
    )
    a("")
    a(
        "This record measures the front end ALONE at its own Csamp load. The "
        "combined front-end + CDAC-array load (`sim/sampling-cdac-handoff`'s "
        "question) needs a testbench instantiating two separate layout tops; "
        "`klt pex` extracts exactly one `--top` per run and swaps a single DUT "
        "`.include`, which is the multi-top gap 2AMLogic/klayout-tools#5494 tracks. "
        "The composed-block run additionally waits on issue #103's top-level LVS. "
        "Neither is a defect of this block's record; both are named so the numbers "
        "above are not over-read as composed-block behavior."
    )
    a("")
    a("## Files")
    a("")
    a("```")
    a(f"{record_id}/")
    a("  sampling_frontend.pex-extract.spice   klt extract --parasitics output")
    a("  extract.json                          klt extract JSON envelope")
    a("  sampling_frontend_pex_reference.spice schematic DUT snapshot (generated)")
    a("  testbench.spice                       pex testbench (single .include swap)")
    a("  pex_request.json                      request as run (OAT carve)")
    a("  pex.json                              klt pex JSON response (delta[])")
    a("  record.md                             this file")
    a("```")
    a("")
    (out / "record.md").write_text("\n".join(lines) + "\n")
    return out / "record.md"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check-env", action="store_true", help="verify klt/PDK/layout and exit")
    ap.add_argument("--pilot", action="store_true", help="one corner (tt/27C/1.8V), local backend")
    ap.add_argument("--record", action="store_true", help="mint an append-only record")
    ap.add_argument("--backend", default=None, help="override klt pex backend (default: local for --pilot, batch otherwise)")
    args = ap.parse_args()

    if args.check_env:
        import subprocess

        info = pex_flow.resolve_pdk()
        gds, latest = pex_flow.latest_layout(BLOCK_DIR, GDS_NAME)
        ver = subprocess.run(
            [str(pex_flow.klt_bin()), "--version"], capture_output=True, text=True, check=True
        ).stdout.strip()
        print(f"klt: {pex_flow.klt_bin()} ({ver})")
        print(f"PDK: {info.variant} at {info.root}")
        print(f"layout: reports/{latest}/{GDS_NAME}")
        return 0

    if args.pilot and args.record:
        print("--pilot and --record are separate invocations", file=sys.stderr)
        return 2
    if args.pilot:
        with tempfile.TemporaryDirectory(prefix="sf-pex-pilot-") as td:
            return run(Path(td), "local", pilot=True, record=False)
    if args.record:
        backend = args.backend or "batch"
        return run(REPORTS_DIR / evidence.new_record_id(), backend, pilot=False, record=True)
    ap.print_help()
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
