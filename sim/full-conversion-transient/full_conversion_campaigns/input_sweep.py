#: The band DR-021's open item names, as fractions of V_REF. The committed
#: DC corner record anchors both ends: the +-0.25 rows converge within
#: +-1 LSB, the +-0.78 rows do not.
SWEEP_BAND_F = (0.25, 0.78)

#: Boundary resolution the committed sweep is located to. AC 3's "largest
#: tested magnitude that converges / smallest that does not" is only
#: meaningful against a named step -- the record states this one.
INPUT_SWEEP_STEP_F = 0.05

#: Swept magnitudes: 0.25 rising in INPUT_SWEEP_STEP_F rungs to 0.75, plus
#: the 0.78 endpoint -- so the sweep is anchored to the committed record's
#: known-converging and known-failing rows and the boundary cannot be
#: quoted outside a tested rung.
SWEEP_MAGNITUDES: tuple[float, ...] = (
    0.25, 0.30, 0.35, 0.40, 0.45, 0.50,
    0.55, 0.60, 0.65, 0.70, 0.75, 0.78,
)

#: Magnitudes no recorded sweep may omit (`check_input_levels()`): the two
#: anchors, which the boundary statement is written against.
REQUIRED_MAGNITUDES: tuple[float, ...] = (0.25, 0.78)

#: The default sweep: BOTH SIGNS of every magnitude, ascending. 24 levels,
#: 24 units in one request.
DEFAULT_INPUT_FRACTIONS: tuple[float, ...] = tuple(
    sorted([-m for m in SWEEP_MAGNITUDES] + [+m for m in SWEEP_MAGNITUDES])
)

#: The informational criterion the boundary is located by: the same +-1 LSB
#: the DC corner campaign reports its per-input verdicts against
#: (`common.CODE_TOLERANCE_LSB`), NOT a spec value.
BOUNDARY_TOLERANCE_LSB = 1

#: Per-UNIT kill (`options.timeout_s`). 2.5x reference-drive-budget's
#: conservative per-unit budget for a deck a third this long: one unit is a
#: ~2.3 us whole-ADC transient, and the 6.3 us DC deck it is sized against
#: ran 219-1290 s per corner point, median ~399 s (n=72), across the
#: committed pre-DR-023 corner logs (campaigns `20260910-190240-2d1d196` ..
#: `20261001-105439-c324f80`, 2026-09-10 to 2026-10-01; minted on
#: ngspice-46 under the then-default solver settings -- above
#: `sim/toolchain.json`'s `ngspice_min_major: 46` floor, predating
#: `ngspice_reference: 47`; the records do not state their host;
#: `Total elapsed time (seconds)` line in each corner log), so 1200 s
#: leaves room for an ss/-40C-style slow point without one stuck unit
#: eating a shard.
DEFAULT_TIMEOUT_S = 1200.0
#: Serial wall-clock budget allowed per unit when sizing shards -- the same
#: sizing rule reference-drive-budget.shard_count() documents: the fleet's
#: whole-job ceiling kills a job and loses EVERY unit in it, so shards are
#: sized as if their units ran serially, against the MEASURED per-unit cost
#: rather than the per-unit kill.
SHARD_SERIAL_BUDGET_S = 600.0
FLEET_JOB_CEILING_S = 3600.0
FLEET_JOB_OVERHEAD_S = 120.0


# --------------------------------------------------------------------------
# Level parsing / validation (pure)
# --------------------------------------------------------------------------
def normalize_input_levels(levels) -> list[float]:
    """Sorted, de-duplicated fractions of V_REF, every one inside the
    DR-021 band in magnitude. The sweep exists to locate THAT band's
    boundary; a level outside it answers a different question and is
    refused rather than silently swept."""
    vals = sorted(set(float(f) for f in levels))
    if not vals:
        raise ValueError("the input-level list is empty")
    lo, hi = SWEEP_BAND_F
    bad = [f for f in vals if not (lo - 1e-12 <= abs(f) <= hi + 1e-12)]
    if bad:
        raise ValueError(
            f"input levels outside [{lo:g}, {hi:g}]*V_REF in magnitude: {bad} -- "
            "the sweep locates the converging-range boundary of that band "
            "(issue #913); levels outside it answer a different question"
        )
    return vals


def parse_input_levels(text: str) -> list[float]:
    """Comma/space-separated fractions of V_REF (`--input-levels`)."""
    try:
        vals = [float(tok) for tok in text.replace(",", " ").split()]
    except ValueError as exc:
        raise ValueError(f"--input-levels: {exc}") from None
    return normalize_input_levels(vals)


def check_input_levels(levels) -> list[float]:
    """normalize_input_levels() plus the campaign's own requirement: EVERY
    --input-sweep run, --record or not, must carry both anchors (each
    REQUIRED_MAGNITUDES value at BOTH signs), so any boundary statement the
    run can support is anchored to the committed record's known-converging
    and known-failing rows and is never reached by interpolation."""
    vals = normalize_input_levels(levels)
    missing = [
        f"{'+' if sign > 0 else '-'}{m:g}"
        for m in REQUIRED_MAGNITUDES
        for sign in (+1, -1)
        if not any(f == sign * m for f in vals)
    ]
    if missing:
        raise ValueError(
            "every --input-sweep run (--record or not) must contain the "
            "band's anchors at both "
            f"signs, {[f'+-{m:g}' for m in REQUIRED_MAGNITUDES]} (the committed "
            "record's known-converging and known-failing rows); missing "
            f"{missing}"
        )
    return vals


def shard_count(n_units: int, *, serial_budget_s: float = SHARD_SERIAL_BUDGET_S,
                ceiling_s: float = FLEET_JOB_CEILING_S,
                overhead_s: float = FLEET_JOB_OVERHEAD_S) -> int:
    """How many batch jobs (`remote.hosts`) the sweep needs so each shard
    fits the fleet's whole-job ceiling even if its units ran SERIALLY --
    reference-drive-budget.shard_count()'s sizing rule, unchanged."""
    per_shard = max(1, int((ceiling_s - overhead_s) // serial_budget_s))
    return max(1, -(-n_units // per_shard))


