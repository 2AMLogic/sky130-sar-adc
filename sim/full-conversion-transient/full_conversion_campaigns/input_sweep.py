"""The converging-range boundary sweep of the unmodified ADC (issue #913).

DR-021's "Open items" list names it: the current architecture resolves the
three mid-scale DC inputs within +-1 LSB and misses the two +-0.78*V_REF
inputs at every ratified corner (records/LATEST, the newest DC corner
campaign), and nothing in the repo says WHERE between those points
conversion stops being correct. This campaign sweeps signed differential
input levels across that band, ONE LEVEL PER `klt sim` UNIT, at the
baseline corner (tt/27C/1.80V) under DR-023's reference solver policy, and
locates the converging-range boundary per sign to the sweep's own step.

Everything here is INFORMATIONAL: a measurement of the AS-COMMITTED
schematic. It grades no row of spec/target-spec.md (DRAFT until #1),
proposes no design change (DR-021's switching scheme is out of scope), and
the record supersedes nothing -- records/LATEST stays on the corner
campaign.

SUBMIT PATH. One `klt sim` request through `harness.klt_sim.submit()`
(issue #865's shared path): this module builds a deck body and a request
and decodes the report; it never builds a `klt sim` argv by hand, never
defines its own submit error type (it aliases
`harness.klt_sim.SubmitError`), and never loops ngspice locally. The deck
body is assembled from the committed
`testbench/input_sweep_tb_fragment.spice` (generated by
`gen_full_conversion_tb.py`, pinned byte-for-byte), read in place and
split by the same shared parser the reference-drive budget splits the DC
fragment with (`harness.klt_sim.split_fragment()`, issue #1030): body ->
netlist, `.meas` cards -> `measurements[]`, `.tran` args ->
`analysis.args`. The swept level is that fragment's own `vin_frac`
top-level parameter, carried as the request's only `corners.params` axis
-- the deck is otherwise identical for every level.

A refusal is evidence too: a hard `klt_sim.SubmitError` mints a NOT RUN
record quoting the refusal reason (the convention of
`sim/cdac-array-transfer/records/20261106-180843-15ea2ea.md`). No local
SPICE fallback exists or is attempted.

This module imports no sibling campaign module except through `common`
and the shared `decode_code_stream` helper; `run_conversion.py` owns the
CLI flag and dispatch (issue #861's per-mode module layout).
"""
