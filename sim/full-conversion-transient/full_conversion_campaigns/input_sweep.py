def write_not_run_record(tag_dir: Path, refusal: str, written_by: str) -> Path:
    """The NOT RUN record of a refused or failed submission (AC 5), after
    the convention of `sim/cdac-array-transfer/records/20261106-180843-
    15ea2ea.md`: the refusal reason quoted verbatim, the deck and request
    committed under `corners/<record-id>/`, and no local SPICE fallback.
    `tag_dir` is the `submit()` workdir holding the already-written
    `request.json` and `tb.spice` (there is no `report.json` to commit)."""
    fragment_text = tb.SWEEP_FRAGMENT_PATH.read_text()
    body = build_body(DUT_NETLIST.read_text(), fragment_text)
    prov, lines = evidence.open_record(
        common.EXPERIMENT_DIR, body, "corners",
        {
            "request.json": (tag_dir / "request.json").read_text(),
            "tb.spice": (tag_dir / "tb.spice").read_text(),
        },
    )
    lines += [
        "- **Claim**: none -- the submit path produced no measurement, so "
        "this record evidences the refusal only. No spec row is claimed or "
        "graded, and it supersedes nothing.",
        "- **Issue**: #913",
        "- **Outcome**: the `klt sim` submission was refused or failed "
        "before any simulation. **No local fallback was run.**",
        "- **Overall**: NOT RUN (no measurement was produced, so the "
        "converging-range boundary is not located by this record)",
        "",
        "## What was run",
        "",
        f"- ONE `klt sim` request, one unit per input level "
        f"(`corners.params` axis `{INPUT_SWEEP_PARAM}`), deck and request "
        f"committed under `corners/{prov.record_id}/`.",
        "- The submission raised:",
        "",
        "```",
        str(refusal).strip(),
        "```",
        "",
        "## Interpretation (checked against the error)",
        "",
        "The sweep says nothing about where conversion stops being correct. "
        "A fleet-capacity refusal (`batch_no_capacity`) is a transient gap, "
        "not a design result; any other refusal is a submit-path failure to "
        "diagnose before re-running. Both are re-run by minting a new "
        "record, never by editing this one.",
        "",
    ]
    lines += evidence.environment_block(
        prov.pdk_line, prov.ng_version, prov.netlist_sha,
        {
            "solver options": common.solver_settings_text(SOLVER_PROFILE),
            "testbench fragment sha256": f"`{evidence.sha256_file(tb.SWEEP_FRAGMENT_PATH)}`",
            "design/sar_adc_top.spice sha256": f"`{evidence.sha256_file(DUT_NETLIST)}`",
        },
    )
    lines += [""]
    lines += evidence.footer_lines(written_by, evidence.NEVER_SUPERSEDES)
    return evidence.close_record(prov, lines, "NOT RUN record")


# --------------------------------------------------------------------------
# Campaign entry point (the dispatcher owns flags; this owns the run)
# --------------------------------------------------------------------------
def run_sweep(fractions, scratch: Path, quiet: bool = False,
              runner=klt_sim.default_runner, hosts: int | None = None,
              ) -> dict:
    """Submit the sweep, decode every level, locate the boundary, and return
    everything the record writer and the dispatcher's stdout need."""
    levels = check_input_levels(fractions)
    units, info, req, d = submit(
        levels, scratch, hosts=hosts or shard_count(len(levels)), runner=runner,
    )
    rows = decode_units(units)
    if not quiet:
        for f in sorted(rows):
            r = rows[f]
            code = "?" if r["code"] is None else str(r["code"])
            err = "n/a" if r["error_lsb"] is None else f"{r['error_lsb']:+d} LSB"
            print(
                f"  {_frac_cell(f)}*V_REF: {code}/{r['ideal_code']} "
                f"({err}) phase={'ok' if r['phase_ok'] else 'FAIL'}"
            )
        bounds = boundary(rows)
        pos, neg = bounds["positive"], bounds["negative"]

        def edge(b, key):
            v = b[key]
            return "n/a" if v is None else f"{v:.2f}*V_REF"

        print(f"  boundary, positive: largest converging {edge(pos, 'largest_converging_f')}, "
              f"smallest failing {edge(pos, 'smallest_failing_f')}")
        print(f"  boundary, negative: largest converging {edge(neg, 'largest_converging_f')}, "
              f"smallest failing {edge(neg, 'smallest_failing_f')}")
    complete = [f for f in rows if rows[f]["complete"]]
    return {
        "levels": levels,
        "rows": rows,
        "info": info,
        "req": req,
        "workdir": d,
        "bounds": boundary(rows),
        "all_read": len(complete) == len(rows),
        "n_complete": len(complete),
    }
