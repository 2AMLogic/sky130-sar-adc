def split_fragment(fragment_text: str) -> tuple[str, list[str], str]:
    """The committed sweep fragment's three pieces for a `klt sim` request
    (circuit body, `.meas` cards, `.tran` arguments) -- the shared
    `harness.klt_sim.split_fragment()` (issue #1030), asserted against
    exactly the names `gen_full_conversion_tb.sweep_measure_names()` emits,
    so a fragment that changes shape fails there instead of silently
    measuring something else."""
    return klt_sim.split_fragment(fragment_text, tb.sweep_measure_names())


def build_body(dut_netlist_text: str, fragment_text: str, *,
               stdcell_include: str = STDCELL_INCLUDE) -> str:
    """The circuit BODY `klt sim` wraps: no `.lib`, no `.temp`, no `.meas`,
    no `.tran`, no `.control`, no `.end` (docs/cli/sim.md, "Netlist
    convention"). The corner's `.lib`/`.temp` cards and the analysis come
    from the request; `vdd_val` (pinned at the nominal baseline supply) and
    `vin_frac` (the swept level, its default of no-op mid-scale) are
    declared here because `corners.params` addresses an existing top-level
    `.param`."""
    frag_body, _meas, _tran = split_fragment(fragment_text)
    dut_lines = [ln for ln in dut_netlist_text.splitlines() if ln.strip().lower() != ".end"]
    lines = [
        "* sim/full-conversion-transient -- converging-range input sweep",
        "* (issue #913, the DR-021 open item) of design/sar_adc_top.spice.",
        f"* Assembled by {RUNNER_REL} --input-sweep.",
        "* Circuit body only: klt sim supplies the .lib corner section, .temp,",
        "* the .meas cards, the .tran analysis and the .control wrapper.",
        "* The stimulus/measurement fragment is this experiment's",
        "* testbench/input_sweep_tb_fragment.spice, used verbatim; the swept",
        "* level is its vin_frac top-level parameter, a fraction of vdd_val.",
        f".param {VDD_PARAM} = {NOMINAL_SUPPLY_V:g}",
        f".param {INPUT_SWEEP_PARAM} = 0.0",
        f".include {stdcell_include}",
        "* VPWR/VGND have no schematic-graph node inside sar_sequencer (see",
        "* design/sar_adc_top.sch's header); the testbench ties them here.",
        ".global VPWR VGND",
        "",
        *dut_lines,
        "",
        frag_body,
        *common.solver_profile_deck_lines(SOLVER_PROFILE),
    ]
    return "\n".join(lines) + "\n"


