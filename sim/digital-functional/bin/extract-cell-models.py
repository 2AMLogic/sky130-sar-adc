#!/usr/bin/env python3
"""Extract the functional (zero-delay, no-power-pin) models of exactly the
sky130_fd_sc_hd cells the digital partition instantiates, from the installed
PDK's own Verilog, into one committed file (models/sky130_fd_sc_hd_subset.v).

Why a subset is committed: a `klt functional-verification` request names its
sources by path, and the PDK lives outside the repo at a host-specific path.
The subset is the PDK's own text (Apache-2.0, headers retained), preprocessed
with `iverilog -E -DFUNCTIONAL -DUNIT_DELAY=#0`, so what the testbench runs
against is the library's behaviour, not a hand-written stand-in. Nothing is
edited; the source file hashes and the PDK revision are recorded in the header.

    python3 sim/digital-functional/bin/extract-cell-models.py [--pdk-root DIR]
"""
import argparse, hashlib, os, re, subprocess, sys, tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
REPO = HERE.parent.parent
CELLS = sorted({
    m for nl in ("layout/sar-sequencer/netlist/sar_sequencer.v",
                 "layout/top-glue/netlist/top_glue.v")
    for m in re.findall(r"sky130_fd_sc_hd__\w+", (REPO / nl).read_text())})


def find_verilog_dir(root):
    cands = [Path(root)] if root else []
    cands += [Path(p) for p in map(os.path.expanduser, (
        "~/.ciel/ciel/sky130/versions/*/sky130A", "~/.volare/sky130A"))]
    for c in cands:
        import glob
        for g in sorted(glob.glob(str(c)), key=lambda x: (".bak" in x, x)) or [str(c)]:
            d = Path(g).resolve() / "libs.ref/sky130_fd_sc_hd/verilog"
            if (d / "sky130_fd_sc_hd.v").is_file():
                return d
    sys.exit("no sky130_fd_sc_hd verilog dir found; pass --pdk-root <.../sky130A>")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pdk-root")
    ap.add_argument("--out", default=str(HERE / "models/sky130_fd_sc_hd_subset.v"))
    a = ap.parse_args()
    vd = find_verilog_dir(a.pdk_root)
    srcs = [vd / "primitives.v", vd / "sky130_fd_sc_hd.v"]
    with tempfile.TemporaryDirectory() as t:
        pre = Path(t) / "pre.v"
        subprocess.run(["iverilog", "-E", "-DFUNCTIONAL", "-DUNIT_DELAY=#0",
                        "-o", str(pre), *map(str, srcs)], check=True)
        text = pre.read_text()
    blocks = {}
    for kind, end in (("module", "endmodule"), ("primitive", "endprimitive")):
        for m in re.finditer(rf"^{kind}\s+(\S+)\s*\(.*?^{end}\b", text, re.S | re.M):
            blocks[m.group(1)] = m.group(0)
    need, todo = [], list(CELLS)
    while todo:
        n = todo.pop()
        if n in need:
            continue
        need.append(n)
        for dep in re.findall(r"sky130_fd_sc_hd__\w+\$?\w*", blocks[n].split("\n", 1)[1]):
            if dep in blocks and dep != n:
                todo.append(dep)
    prims = sorted(n for n in need if blocks[n].startswith("primitive"))
    mods = sorted(n for n in need if n in CELLS)
    rev = vd.parts[vd.parts.index("versions") + 1] if "versions" in vd.parts else vd
    hdr = ["// GENERATED by sim/digital-functional/bin/extract-cell-models.py -- do not edit.",
           "// Functional (zero-delay, no power pins) models of the cells the digital",
           "// partition instantiates, copied unmodified from the sky130_fd_sc_hd Verilog",
           "// (SkyWater PDK, Apache-2.0) after `iverilog -E -DFUNCTIONAL -DUNIT_DELAY=#0`.",
           f"// PDK Verilog dir revision: {rev}"]
    hdr += [f"// source sha256 {hashlib.sha256(s.read_bytes()).hexdigest()}  {s.name}" for s in srcs]
    hdr += ["// cells: " + " ".join(mods), "`timescale 1ns / 1ps", ""]
    body = "\n\n".join(blocks[n] for n in prims + mods)
    Path(a.out).write_text("\n".join(hdr) + body + "\n")
    print(f"wrote {a.out}: {len(prims)} primitives, {len(mods)} cells")


main()
